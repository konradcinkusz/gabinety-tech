// Generates web/src/lib/api/generated/<service>.ts from each service's OpenAPI document.
//   node scripts/gen-types.mjs [--allow-missing] [--sources <json>] [--out <dir>]
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
export const DEFAULT_SOURCES = path.join(here, "openapi-sources.json");
export const DEFAULT_OUT = path.join(here, "..", "src", "lib", "api", "generated");
const HEADER = "// Generated by scripts/gen-types.mjs from the service's /openapi/v1.json. Do not edit.\n\n";

export function parseArgs(argv) {
  const a = { allowMissing: false, sources: DEFAULT_SOURCES, out: DEFAULT_OUT };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--allow-missing") a.allowMissing = true;
    else if (argv[i] === "--sources") a.sources = path.resolve(argv[++i]);
    else if (argv[i] === "--out") a.out = path.resolve(argv[++i]);
    else throw new Error(`unknown argument ${argv[i]}`);
  }
  return a;
}

/** Fetches each source and returns { files: Map(name -> text), skipped: string[] }. Throws for a missing one unless allowed. */
export async function render({ sources, allowMissing }) {
  const map = JSON.parse(await readFile(sources, "utf8"));
  const files = new Map();
  const skipped = [];
  for (const [name, url] of Object.entries(map)) {
    let schema;
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(10_000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      schema = await res.json();
    } catch (e) {
      if (!allowMissing) throw new Error(`${name}: ${url} did not answer (${e.message}). Use --allow-missing to skip.`);
      skipped.push(name);
      console.log(`skipped ${name}: ${url} did not answer`);
      continue;
    }
    files.set(`${name}.ts`, HEADER + astToString(await openapiTS(schema)));
  }
  return { files, skipped };
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const { files } = await render(args);
  await mkdir(args.out, { recursive: true });
  for (const [file, text] of files) {
    await writeFile(path.join(args.out, file), text);
    console.log(`wrote ${path.join(args.out, file)}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(e.message);
    process.exit(1);
  });
}
