type Leaves<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string ? `${P}${K}` : T[K] extends readonly unknown[] ? never : Leaves<T[K], `${P}${K}.`>;
}[keyof T & string];
export type PKey = Leaves<typeof ppl>;

export function pp(key: PKey, params?: Record<string, string | number>): string {
  let node: unknown = ppl;
  for (const part of key.split(".")) node = (node as Record<string, unknown>)[part];
  const text = typeof node === "string" ? node : key;
  return params ? text.replace(/\{(\w+)\}/g, (w, n: string) => (n in params ? String(params[n]) : w)) : text;
}
